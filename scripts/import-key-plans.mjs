// Bundle curated key-building plans for the game.
//
//   npm run import:keyplans
//
// Reads assets/key-plans/<id>.plan.json and writes src/domain/keyPlans.generated.ts,
// so the world builder (browser and the Node smoke test) gets the plans without a
// fetch or JSON-module imports. The JSON files stay the source of truth (the dev
// drawings and materials pages read them directly).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const dir = join(ROOT, 'assets', 'key-plans');
const plans = {};
for (const f of readdirSync(dir).filter((n) => n.endsWith('.plan.json')).sort()) {
  const plan = JSON.parse(readFileSync(join(dir, f), 'utf8'));
  if (!plan.id || !plan.frame || !Array.isArray(plan.walls) || !Array.isArray(plan.rooms)) {
    throw new Error(`${f}: missing id / frame / walls / rooms`);
  }
  plans[plan.id] = plan;
}
const out = `// AUTO-GENERATED by scripts/import-key-plans.mjs from assets/key-plans/*.plan.json — do not hand-edit.
// Rerun: npm run import:keyplans
import type { BuildingPlan } from './keyPlan.js';

// Parsed from a string: the curated JSON carries notes and extra fields beyond BuildingPlan.
export const KEY_PLANS: Record<string, BuildingPlan> = JSON.parse(${JSON.stringify(JSON.stringify(plans))});
`;
writeFileSync(join(ROOT, 'src', 'domain', 'keyPlans.generated.ts'), out);
console.log(`[import:keyplans] ${Object.keys(plans).length} plan(s): ${Object.keys(plans).join(', ')} -> src/domain/keyPlans.generated.ts`);
